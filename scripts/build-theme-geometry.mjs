import { readdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { format, resolveConfig } from 'prettier';

// Cast shadows belong to the material, not to the painted character's center.
async function opaqueGeometry(file) {
  const { data, info } = await sharp(file)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let left = info.width,
    top = info.height,
    right = -1,
    bottom = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] < 200) continue;
      left = Math.min(left, x);
      right = Math.max(right, x);
      top = Math.min(top, y);
      bottom = Math.max(bottom, y);
    }
  }
  if (right < left) throw new Error(`No opaque artwork in ${file}`);
  return {
    size: [info.width, info.height],
    center: [(left + right + 1) / 2 / info.width, (top + bottom + 1) / 2 / info.height],
  };
}

const centers = {};
const buttonGeometry = {};
let buttonCss = '/* Generated by scripts/build-theme-geometry.mjs from opaque artwork bounds. */\n';
for (const theme of ['picnic', 'porcelain', 'maple']) {
  centers[theme] = {};
  const directory = `art/runtime-sources/themes/${theme}/pieces`;
  for (const file of (await readdir(directory)).filter((name) => name.endsWith('.png')).sort()) {
    const geometry = await opaqueGeometry(`${directory}/${file}`);
    centers[theme][file.slice(0, -4)] = geometry.center.map((value) =>
      Number((value * 100).toFixed(3)),
    );
  }
  buttonGeometry[theme] = {};
  for (const material of ['well', 'button-secondary', 'button-primary']) {
    const geometry = await opaqueGeometry(`art/runtime-sources/themes/${theme}/${material}.png`);
    buttonGeometry[theme][material] = {
      size: geometry.size,
      center: geometry.center.map((value) => Number(value.toFixed(6))),
    };
    const selectors =
      material === 'well'
        ? [`.mobile-shell[data-theme='${theme}'] .mobile-icon-button`]
        : material === 'button-primary'
          ? [
              `.mobile-shell[data-theme='${theme}'] .mobile-control.is-primary`,
              `.mobile-dialog[data-theme='${theme}'] .mobile-control.is-primary`,
            ]
          : [
              `.mobile-shell[data-theme='${theme}'] .mobile-level`,
              `.mobile-shell[data-theme='${theme}'] .mobile-control`,
              `.mobile-dialog[data-theme='${theme}'] .mobile-control`,
            ];
    buttonCss += `${selectors.join(',\n')} {\n--button-offset-x: ${((geometry.center[0] - 0.5) * 100).toFixed(3)}%;\n--button-offset-y: ${((geometry.center[1] - 0.5) * 100).toFixed(3)}%;\n}\n`;
  }
}
const target = 'src/mobile/theme-piece-centers.ts';
const source = `// Generated by scripts/build-theme-geometry.mjs from opaque artwork bounds.\nexport const themePieceCenters = ${JSON.stringify(centers, null, 2)} as const;\n`;
await writeFile(
  target,
  await format(source, { ...(await resolveConfig(target)), parser: 'typescript' }),
);
const buttonTarget = 'src/game/theme-button-geometry.ts';
await writeFile(
  buttonTarget,
  await format(
    `// Generated by scripts/build-theme-geometry.mjs from opaque artwork bounds.\nexport const themeButtonGeometry = ${JSON.stringify(buttonGeometry)} as const;\n`,
    { ...(await resolveConfig(buttonTarget)), parser: 'typescript' },
  ),
);
const cssTarget = 'src/mobile/theme-button-centers.css';
await writeFile(
  cssTarget,
  await format(buttonCss, { ...(await resolveConfig(cssTarget)), parser: 'css' }),
);
